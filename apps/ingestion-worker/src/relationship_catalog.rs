//! The relationship catalog — one enumerable, fully-specified declaration per relationship type that
//! executable code can emit.
//!
//! ## Why this module exists
//!
//! The generated manifest used to be derived from `ontology::REGISTRY` alone. But `REGISTRY` is not the
//! only emitter: `normalizer::relationships_for` carried a second mapping as an inline `match`, and a
//! `match` is not enumerable — nothing could walk it to discover what it emits. The result was a
//! catalog-generation defect, not a missing row: **86 of 89 legacy relationship types were absent from
//! the manifest**, and therefore from the traversal allowlist derived from it. `HAS_EDUCATION_RECORD`
//! (16 live edges in production) was simply the one that had data.
//!
//! The fix is structural. Every emitter is now an enumerable table (`ontology::REGISTRY`,
//! `ontology::LEGACY_USER_EDGES`, and the declared special relationships), and this catalog declares a
//! policy for each relationship those tables can produce. `catalog_covers_every_emittable_relationship`
//! fails CI when an emitter can produce a relationship with no catalog row, so a new edge cannot ship
//! without an explicit traversal-policy decision.
//!
//! ## Traversability is a per-context policy, not a Boolean
//!
//! A single `traversable: bool` cannot express "the personal advisor may not follow this, but a provider
//! advisor or an internal audit may". Provider and Arcana B2B edges describe the service relationship
//! *around* a user rather than facts *inside* their life model; making them universally traversable
//! would widen personal retrieval into provider-operational data. Each relationship therefore declares
//! `permitted_contexts` and `permitted_principals`, and traversal planning asks
//! [`is_traversable_in`] rather than reading a flag.
//!
//! **Fail closed.** [`spec_for`] returns `None` for an undeclared relationship, and both ingestion
//! validation and traversal planning treat `None` as "refuse", never as "allow with defaults". There is
//! no inferred fallback policy: an unknown relationship is a build failure, not a guess.
//!
//! Regenerate the JSON contract with:
//!   cargo test -p ingestion-worker export_relationship_manifest -- --ignored

use crate::ontology::{LEGACY_USER_EDGES, REGISTRY};

/// Which executable emitter can produce this relationship.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum RelOrigin {
    /// Declared in `ontology::REGISTRY` — the primary, FK-capable registry.
    PrimaryRegistry,
    /// Declared in `ontology::LEGACY_USER_EDGES` — user-anchored, not yet migrated to the registry.
    LegacyNormalizer,
    /// A special relationship with a hand-written emitter (today: the `RELATED_TO` fallback).
    SpecialFallback,
    /// No emitter today. Declared for vocabulary completeness; the planner may not assume availability.
    Planned,
}

/// Whether a writer exists. Whether a *corpus* contains the edge is a runtime question answered by the
/// reconciliation and evaluation harnesses — never assumed here.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum RelLifecycle {
    Implemented,
    Planned,
    Deprecated,
    Unsupported,
    DerivedOnly,
}

/// What kind of thing the relationship asserts.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Classification {
    PersonalLifeModelFact,
    DerivedAnalytic,
    SensitivePersonal,
    ProviderB2b,
    OperationalProvenance,
    Compatibility,
    Deprecated,
    PlannedNotImplemented,
}

/// Which data plane the edge lives in.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum DataPlane {
    PersonalLifeModel,
    DerivedAnalytic,
    Operational,
    ProviderB2b,
    Central,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Sensitivity {
    Low,
    Medium,
    High,
    Restricted,
}

/// The retrieval context asking to follow an edge. Policy is expressed per context so future
/// provider-facing traversal is an added context, not a widened Boolean.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum QueryContext {
    PersonalAdvisor,
    ProviderAdvisor,
    OrgAdministrator,
    InternalAudit,
    CentralKnowledge,
}

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum PrincipalType {
    User,
    Provider,
    OrgAdministrator,
    System,
}

/// Edge direction, in the emitter's terms: `(source)-[rel]->(target)`.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum Direction {
    SourceToTarget,
}

/// The full declared policy for one relationship type.
#[derive(Clone, Copy, Debug)]
pub struct RelationshipSpec {
    pub rel_type: &'static str,
    pub origin: RelOrigin,
    pub lifecycle: RelLifecycle,
    pub classification: Classification,
    pub data_plane: DataPlane,
    pub sensitivity: Sensitivity,
    pub semantic_domain: &'static str,
    pub family: &'static str,
    pub weight: f32,
    pub direction: Direction,
    pub source_node_types: &'static [&'static str],
    pub target_node_types: &'static [&'static str],
    /// Contexts allowed to traverse this edge. EMPTY means no context may — not "all".
    pub permitted_contexts: &'static [QueryContext],
    pub permitted_principals: &'static [PrincipalType],
    /// Maximum hops this edge may be followed for. 0 = never expand through it.
    pub max_hops: u8,
    pub provenance_required: bool,
    pub citation_eligible: bool,
}

impl RelationshipSpec {
    /// Whether `ctx` may follow this edge. Absence of the context is a refusal.
    pub fn is_traversable_in(&self, ctx: QueryContext) -> bool {
        self.max_hops > 0 && self.permitted_contexts.contains(&ctx)
    }

    /// Whether the personal advisor may surface this edge at all.
    pub fn personal_advisor_eligible(&self) -> bool {
        self.is_traversable_in(QueryContext::PersonalAdvisor)
    }
}

