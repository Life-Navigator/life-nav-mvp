/// The declared policy for a relationship, or `None` if undeclared.
///
/// `None` means REFUSE. Callers must not substitute a default policy — that is the whole point of
/// failing closed.
pub fn spec_for(rel_type: &str) -> Option<&'static RelationshipSpec> {
    CATALOG.iter().find(|s| s.rel_type == rel_type)
}

/// Whether `ctx` may follow `rel_type`. Undeclared relationships are refused.
pub fn is_traversable_in(rel_type: &str, ctx: QueryContext) -> bool {
    spec_for(rel_type).is_some_and(|s| s.is_traversable_in(ctx))
}

/// Relationship types traversable in `ctx`, sorted. This is what the planner allowlist derives from.
pub fn traversable_in(ctx: QueryContext) -> Vec<&'static str> {
    let mut v: Vec<&'static str> = CATALOG
        .iter()
        .filter(|s| s.is_traversable_in(ctx))
        .map(|s| s.rel_type)
        .collect();
    v.sort_unstable();
    v
}

/// Every relationship type an executable emitter can produce today.
///
/// Walks the enumerable emitter tables. This is deliberately NOT derived from live graph contents:
/// support is a property of the code, and a relationship with no data yet is still supported.
pub fn emittable_relationship_types() -> Vec<&'static str> {
    let mut v: Vec<&'static str> = REGISTRY
        .iter()
        .flat_map(|(_, edges)| edges.iter().map(|e| e.rel_type))
        .collect();
    v.extend(LEGACY_USER_EDGES.iter().map(|(_, r)| *r));
    v.push("RELATED_TO");
    v.sort_unstable();
    v.dedup();
    v
}
